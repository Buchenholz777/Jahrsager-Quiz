-- ZEITSPUR – Initiales Schema (PostgreSQL 15+, Supabase-kompatibel)
-- Konvention: Dieselben Dateien werden von `npm run db:migrate` (lokal/PGlite oder DATABASE_URL)
-- und von `supabase db push` verwendet.

create table events (
  id uuid primary key default gen_random_uuid(),
  slug text not null unique,
  status text not null default 'entwurf'
    check (status in ('entwurf','in_pruefung','freigegeben','eingeplant','veroeffentlicht')),
  is_demo boolean not null default false,
  version int not null default 1,
  category text not null,
  difficulty smallint not null default 2 check (difficulty between 1 and 3),

  -- Vor dem Tipp sichtbar (muss frei von Zeitangaben sein)
  neutral_title text not null,
  description text not null,
  image_alt text not null,
  image_credit_short text not null default '',

  -- Lösung / Auflösung (nie vor dem Tipp an den Client)
  correct_year smallint not null check (correct_year between 1900 and 2020),
  exact_date text,
  photo_date text,
  public_title text not null,
  explanation_what text not null,
  explanation_why text not null,
  explanation_detail text not null,
  background text not null default '',
  sources jsonb not null default '[]'::jsonb,

  -- Bild und Rechte
  image_id text,
  image_ext text,
  image_width int,
  image_height int,
  image_is_placeholder boolean not null default false,
  image_photographer text not null default '',
  image_institution text not null default '',
  image_credit_full text not null default '',
  image_license text not null default '',
  image_license_url text not null default '',
  image_source_url text not null default '',
  image_edits text not null default '',

  -- Redaktionelle Prüfschritte (rights, facts, photoMatchesEvent)
  checks jsonb not null default '{}'::jsonb,
  knowledge_enabled boolean not null default false,

  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  published_at timestamptz
);
create index events_status_idx on events(status);

-- Jede gespeicherte Fassung eines Ereignisses (Nachvollziehbarkeit, Konzept 10/11)
create table event_revisions (
  event_id uuid not null references events(id) on delete cascade,
  version int not null,
  snapshot jsonb not null,
  note text not null default '',
  created_at timestamptz not null default now(),
  primary key (event_id, version)
);

create table daily_packs (
  id uuid primary key default gen_random_uuid(),
  number int generated by default as identity unique,
  pack_date date not null unique,
  status text not null default 'geplant' check (status in ('geplant','veroeffentlicht')),
  created_at timestamptz not null default now()
);

create table daily_pack_events (
  pack_id uuid not null references daily_packs(id) on delete cascade,
  position smallint not null check (position between 1 and 5),
  event_id uuid not null references events(id),
  primary key (pack_id, position),
  unique (pack_id, event_id)
);

create table players (
  id uuid primary key default gen_random_uuid(),
  created_at timestamptz not null default now(),
  last_seen_at timestamptz not null default now()
);

create table games (
  id uuid primary key default gen_random_uuid(),
  player_id uuid not null references players(id) on delete cascade,
  pack_id uuid not null references daily_packs(id),
  mode text not null check (mode in ('daily','practice')),
  official boolean not null default false,
  status text not null default 'laufend' check (status in ('laufend','abgeschlossen')),
  scoring_version int not null,
  total_points int not null default 0,
  started_at timestamptz not null default now(),
  completed_at timestamptz
);
-- Pro Spieler und Tagespaket gibt es genau eine offizielle Wertung.
create unique index games_one_official on games(player_id, pack_id) where official;
create unique index games_one_running_practice on games(player_id, pack_id) where not official and status = 'laufend';
create index games_player_idx on games(player_id, started_at desc);

create table game_rounds (
  game_id uuid not null references games(id) on delete cascade,
  position smallint not null check (position between 1 and 5),
  event_id uuid not null references events(id),
  event_version int not null,
  status text not null default 'offen' check (status in ('offen','getippt','ohne_tipp')),
  guess_year smallint,
  correct_year smallint,
  difference smallint,
  points int,
  answered_at timestamptz,
  primary key (game_id, position)
);

create table error_reports (
  id uuid primary key default gen_random_uuid(),
  event_id uuid references events(id) on delete set null,
  game_id uuid,
  message text not null check (char_length(message) between 5 and 2000),
  status text not null default 'offen' check (status in ('offen','bearbeitet','verworfen')),
  resolution_note text not null default '',
  created_at timestamptz not null default now()
);

-- Datensparsame Eigenmessung: keine Personen-ID, keine IP, keine Cookies.
create table analytics_events (
  id bigint generated always as identity primary key,
  created_at timestamptz not null default now(),
  day date not null,
  name text not null,
  props jsonb not null default '{}'::jsonb
);
create index analytics_day_name_idx on analytics_events(day, name);

-- Zugriff nur über die Server-Verbindung (Least Privilege): RLS ohne Policies sperrt anon/authenticated.
alter table events enable row level security;
alter table event_revisions enable row level security;
alter table daily_packs enable row level security;
alter table daily_pack_events enable row level security;
alter table players enable row level security;
alter table games enable row level security;
alter table game_rounds enable row level security;
alter table error_reports enable row level security;
alter table analytics_events enable row level security;

do $$
begin
  if exists (select 1 from pg_roles where rolname = 'anon') then
    revoke all on all tables in schema public from anon;
  end if;
  if exists (select 1 from pg_roles where rolname = 'authenticated') then
    revoke all on all tables in schema public from authenticated;
  end if;
end $$;
